#!/usr/bin/env python3
"""Dump the ROM tables the port is built from, as JSON and Markdown, so the plan's appendices can be checked.

Reads the same sources `build_assets.py` does (the extracted `bin/dat` tree, or `ext/Original.nes` through
`src/bins.xml`), with the same decoding, and writes only under --out-dir (default `build/dump`). It never writes the ROM
anywhere. Rerunning it after a change to the decoders shows what moved.

    python3 tools/dump_tables.py [--source-root ..] [--out-dir build/dump]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import actors  # noqa: E402
import build_assets as B  # noqa: E402
import underworld as U  # noqa: E402

SIZE = B.LEVEL_BLOCK_TABLE_SIZE
ATTRIBUTES = "ABCDEF"
UW_LEVELS = range(1, 10)


def screen_name(room: int) -> str:
    """Column letter A-P and row 1-8: A1 is room $00, P8 is $7F."""
    return f"{chr(ord('A') + (room & 15))}{(room >> 4) + 1}"


def split_block(block: bytes) -> list[bytes]:
    return [block[i * SIZE:(i + 1) * SIZE] for i in range(6)]


def dump_overworld(source_root: Path) -> dict:
    attrs = split_block(B.require_binary(source_root, B.LEVEL_BLOCK_OW_NAME))
    info = B.require_binary(source_root, B.LEVEL_INFO_OW_NAME)
    foe = list(info[B.LEVEL_INFO_FOE_COUNTS:B.LEVEL_INFO_FOE_COUNTS + 4])
    screens = []
    for room in range(128):
        a, b, c, d, e, f = (table[room] for table in attrs)
        screens.append({
            "room": room, "name": screen_name(room),
            "attributes": dict(zip(ATTRIBUTES, (a, b, c, d, e, f))),
            "destination": b >> 2,                       # 1-9 a dungeon, $10 and up a cave type
            "monster_list": (c & 0x3F) | (0x40 if d & 0x80 else 0),
            "monster_count_class": c >> 6,
            "monster_count": foe[c >> 6],
        })
    return {"start_room": info[B.LEVEL_INFO_START_ROOM_ID], "start_y": info[B.LEVEL_INFO_START_Y],
            "foe_counts": foe, "screens": screens}


def dump_underworld(source_root: Path, level: int, lists: list[list[int]]) -> dict:
    quest_block = "UW1Q1" if level <= 6 else "UW2Q1"
    attrs = split_block(B.require_binary(source_root, f"dat/LevelBlock{quest_block}.dat"))
    info = B.require_binary(source_root, f"dat/LevelInfoUW{level}.dat")
    start = info[B.LEVEL_INFO_START_ROOM_ID]
    foe = list(info[B.LEVEL_INFO_FOE_COUNTS:B.LEVEL_INFO_FOE_COUNTS + 4])
    rooms = []
    for room in U.level_rooms(start, info, attrs[0], attrs[1], attrs[3]):
        a, b, c, d, e, f = (table[room] for table in attrs)
        record = actors._room_info(room, (attrs[2], attrs[3], attrs[4], attrs[5]), foe, info, lists=lists)
        rooms.append({
            "room": room, "name": screen_name(room),
            "attributes": dict(zip(ATTRIBUTES, (a, b, c, d, e, f))),
            "layout": d & 0x3F,
            "item": 0xFF if (e & 0x1F) == 3 else e & 0x1F,
            "dark": bool(e & 0x80),
            "secret_trigger": f & 7,
            "push_block": bool(d & 0x40),
            "monster_list": (c & 0x3F) | (0x40 if d & 0x80 else 0),
            "monster_count": record[0],
            "monsters": [actors.MONSTER_TYPES[m] for m in record[6:6 + record[0]]],
        })
    return {"level": level, "start_room": start, "start_y": info[B.LEVEL_INFO_START_Y],
            "triforce_room": info[B.LEVEL_INFO_TRIFORCE_ROOM_ID], "foe_counts": foe, "rooms": rooms}


def check_rom(overworld: dict) -> list[str]:
    """The checks the plan's method appendix names: start room, start Y, overworld group sizes."""
    problems = []
    if overworld["start_room"] != 0x77:
        problems.append(f"start room {overworld['start_room']:#x}, expected 0x77")
    if overworld["start_y"] != 0x8D:
        problems.append(f"start Y {overworld['start_y']:#x}, expected 0x8D")
    if overworld["foe_counts"] != [1, 4, 5, 6]:
        problems.append(f"overworld group sizes {overworld['foe_counts']}, expected [1, 4, 5, 6]")
    return problems


def markdown(tables: dict) -> str:
    out = ["# ROM tables", "", "Generated by `tools/dump_tables.py`; do not edit.", ""]
    ow = tables["overworld"]
    out += ["## Overworld", "",
            f"Start room ${ow['start_room']:02X}, start Y ${ow['start_y']:02X}, group sizes {ow['foe_counts']}.", "",
            "| Screen | Room | Destination | Monster list | Count | Attributes A-F |", "|---|---|---|---|---|---|"]
    for s in ow["screens"]:
        attrs = " ".join(f"{s['attributes'][k]:02X}" for k in ATTRIBUTES)
        out.append(f"| {s['name']} | ${s['room']:02X} | ${s['destination']:02X} | ${s['monster_list']:02X} | "
                   f"{s['monster_count']} | {attrs} |")
    for level in tables["underworld"]:
        out += ["", f"## Level {level['level']}", "",
                f"Start room ${level['start_room']:02X}, triforce room ${level['triforce_room']:02X}, "
                f"{len(level['rooms'])} rooms, group sizes {level['foe_counts']}.", "",
                "| Room | Layout | Item | Trigger | Dark | Monsters (NES types) |", "|---|---|---|---|---|---|"]
        for r in level["rooms"]:
            item = "-" if r["item"] == 0xFF else f"${r['item']:02X}"
            monsters = " ".join(f"{m:02X}" for m in r["monsters"]) or "-"
            out.append(f"| ${r['room']:02X} | ${r['layout']:02X} | {item} | {r['secret_trigger']} | "
                       f"{'dark' if r['dark'] else ''} | {monsters} |")
    out += ["", "## Monster lists ($62 and up)", "", "| List | Types |", "|---|---|"]
    for index, types in enumerate(tables["monster_lists"]):
        out.append(f"| ${0x62 + index:02X} | {' '.join(f'{t:02X}' for t in types)} |")
    return "\n".join(out) + "\n"


def collect(source_root: Path) -> dict:
    lists = actors.overworld_monster_lists(source_root)
    return {
        "overworld": dump_overworld(source_root),
        "underworld": [dump_underworld(source_root, level, lists) for level in UW_LEVELS],
        "monster_lists": lists,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source-root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--out-dir", type=Path, default=Path(__file__).resolve().parents[1] / "build" / "dump")
    args = parser.parse_args()
    tables = collect(args.source_root)
    problems = check_rom(tables["overworld"])
    if problems:
        sys.exit("This does not look like the Europe Rev 1 ROM:\n  " + "\n  ".join(problems))
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "tables.json").write_text(json.dumps(tables, indent=1) + "\n", encoding="utf-8")
    (args.out_dir / "tables.md").write_text(markdown(tables), encoding="utf-8")
    print(f"Wrote {args.out_dir / 'tables.json'} and {args.out_dir / 'tables.md'}: "
          f"128 overworld screens, {sum(len(l['rooms']) for l in tables['underworld'])} dungeon rooms in 9 levels")


if __name__ == "__main__":
    main()
